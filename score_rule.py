def grade_level(total: float):
    """根据综合满意度指数（0-100）返回评级与解读。"""
    for threshold, level, desc in GRADE_LEVELS:
        if total >= threshold:
            return level, desc
    return GRADE_LEVELS[-1][1], GRADE_LEVELS[-1][2]


