# ============================================================
# 一、标准化打分区间（0-10 分统一标准）
# ============================================================
SCORE_BANDS = [
    (9.0, "极致满意", "状态优秀，无任何短板"),
    (7.0, "良好满意", "状态正常，轻微可优化"),
    (5.0, "基本达标", "勉强适应，存在明显不足"),
    (3.0, "不满意", "体验较差，猫咪出现负面行为"),
    (0.0, "极度不满", "猫咪应激、抵触、抗拒家庭/主人"),
]


def score_band(score: float):
    """根据 0-10 分返回所属打分区间描述。"""
    for threshold, band, desc in SCORE_BANDS:
        if score >= threshold:
            return band, desc
    return SCORE_BANDS[-1][1], SCORE_BANDS[-1][2]


