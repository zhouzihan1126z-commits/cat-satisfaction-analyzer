# 六、辅助查询函数
# ============================================================
def dimension_map():
    """返回 {维度key: 维度dict}。"""
    return {d["key"]: d for d in DIMENSIONS}


def all_indicators():
    """返回 [(维度dict, 指标dict), ...]，按维度顺序展开全部 22 项指标。"""
    result = []
    for dim in DIMENSIONS:
        for ind in dim["indicators"]:
            result.append((dim, ind))
    return result


def indicator_map():
    """返回 {指标key: (维度dict, 指标dict)}。"""
    return {ind["key"]: (dim, ind) for dim, ind in all_indicators()}


def total_weight():
    """维度权重之和（应恒等于 100）。"""
    return sum(d["weight"] for d in DIMENSIONS)


def validate_config():
    """校验配置完整性：权重和、指标 key 唯一性。"""
    errors = []
    tw = total_weight()
    if tw != 100:
        errors.append(f"维度权重之和应为100，当前为 {tw}")
    seen = set()
    for dim, ind in all_indicators():
        if ind["key"] in seen:
            errors.append(f"指标 key 重复: {ind['key']}")
        seen.add(ind["key"])
    return errors
